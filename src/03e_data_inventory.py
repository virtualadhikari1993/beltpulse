"""Step 3e - One table: original data -> LLM labels -> physics-propagated labels -> training samples, per video.

Run:  .venv\\Scripts\\python src\\03e_data_inventory.py
Writes docs/data_inventory.md
"""
import os
import json
from collections import Counter

from common import ROOT, videos, frames_of, anomaly_frames, split_of, NORMAL_VIDEOS

_lab = json.load(open(os.path.join(ROOT, "data", "labels", "keyframe_boxes_llm.json")))
kf = _lab["keyframes"]
extra = set(_lab.get("extra_keyframes", {}).get("keys", []))
boxes = json.load(open(os.path.join(ROOT, "data", "labels", "boxes.json")))
samples = json.load(open(os.path.join(ROOT, "data", "samples", "samples.json")))
anom = anomaly_frames()

KIND = {"7_wood": "wooden sticks", "canga": "orange rock + plastic", "jaspilito": "pink rock", "things": "tools / wooden block"}


def kind(v):
    if v in NORMAL_VIDEOS:
        return "ore only (normal)"
    return next(t for k, t in KIND.items() if k in v)


rows, tot = [], Counter()
for v in videos():
    n_frames = len(frames_of(v))
    n_anom = len(anom.get(v, []))
    n_kf = sum(1 for k in kf if k.startswith(v + "/"))
    n_extra = sum(1 for k in extra if k.startswith(v + "/"))
    n_lab = sum(1 for k in boxes if k.startswith(v + "/"))
    n_samp = sum(1 for s in samples if s["video"] == v)
    r = dict(video=v.replace("boardcamera_", ""), kind=kind(v), split=split_of(v), frames=n_frames, anom=n_anom,
             llm=n_kf - n_extra, extra=n_extra, prop=n_lab - n_kf, labeled=n_lab, samples=n_samp)
    rows.append(r)
    for k in ["frames", "anom", "llm", "extra", "prop", "labeled", "samples"]:
        tot[k] += r[k]

hdr = ("| video | what's in it | split | frames in video | frames marked 'has object' by dataset authors "
       "| labeled by LLM (keyframes) | labeled by LLM (extra, rolling) | labeled by physics (propagated) | labeled total "
       "| training examples built (step 04) |")
lines = ["# Data inventory: from raw video to training examples", "",
         "Generated by `src/03e_data_inventory.py`. Re-run after relabelling.", "",
         "## How the columns relate", "```",
         "frames in video                       every photo extracted from the video (≈120 per second)",
         "  └─ marked 'has object' by authors   frame-level yes/no from the dataset (no location)",
         "       ├─ labeled by LLM               keyframes where boxes were drawn (Claude, dry run)",
         "       ├─ labeled by LLM (extra)       extra keyframes where objects roll/slide (03f), reviewed ground truth",
         "       └─ labeled by physics           boxes copied from the 2 surrounding keyframes, shifted by belt motion",
         "                                       (two-keyframe correction, see 03c)",
         "            = labeled total            frames that now have boxes",
         "training examples (step 04)           every 2nd labeled frame (+ its 2 neighbours) and every 6th frame",
         "                                      of the ore-only videos (answer = all zeros)",
         "```", "", "## Per video", "", hdr, "|" + "---|" * 10]
for r in rows:
    lines.append(f"| {r['video']} | {r['kind']} | {r['split']} | {r['frames']:,} | {r['anom'] or '–'} | {r['llm'] or '–'} | "
                 f"{r['extra'] or '–'} | {r['prop'] or '–'} | {r['labeled'] or '–'} | {r['samples']} |")
lines.append(f"| **total** | | | **{tot['frames']:,}** | **{tot['anom']:,}** | **{tot['llm']}** | **{tot['extra']}** | "
             f"**{tot['prop']:,}** | **{tot['labeled']:,}** | **{tot['samples']:,}** |")

lines += ["", "## Summary by kind", "",
          "| kind | videos | frames | labeled by LLM | LLM extra (rolling) | labeled by physics | training examples |",
          "|---|---|---|---|---|---|---|"]
by = {}
for r in rows:
    b = by.setdefault(r["kind"], Counter())
    b["videos"] += 1
    for k in ["frames", "llm", "extra", "prop", "samples"]:
        b[k] += r[k]
for k, b in by.items():
    lines.append(f"| {k} | {b['videos']} | {b['frames']:,} | {b['llm'] or '–'} | {b['extra'] or '–'} | {b['prop'] or '–'} | {b['samples']:,} |")

n_box_llm = sum(len(b) for b in kf.values())
n_box_all = sum(len(b) for b in boxes.values())
lines += ["", "## In one sentence",
          f"{len(rows)} videos with {tot['frames']:,} frames → the authors marked {tot['anom']:,} as containing an object → "
          f"the LLM drew {n_box_llm} boxes on {tot['llm'] + tot['extra']} of them ({tot['llm']} regular keyframes + "
          f"{tot['extra']} extra keyframes where objects roll) → belt physics spread these to {tot['prop']:,} more frames "
          f"({tot['labeled']:,} labeled frames, {n_box_all:,} boxes) → step 04 built {tot['samples']:,} training examples "
          f"({sum(s['split'] == 'train' for s in samples):,} train / {sum(s['split'] == 'val' for s in samples)} val / "
          f"{sum(s['split'] == 'test' for s in samples)} test).",
          "",
          f"Why labeled total ({tot['labeled']:,}) < marked by authors ({tot['anom']:,}): frames further than 500 px of belt travel "
          "from any keyframe are left unlabeled (propagation would be too inaccurate)."]
open(os.path.join(ROOT, "docs", "data_inventory.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("written: docs/data_inventory.md")
